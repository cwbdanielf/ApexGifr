    @staticmethod
    def draw_character(
        pixels,
        width: int,
        height: int,
        code: int,
        x: int,
        y: int,
        color: int = 1,
        size: int = 1,
    ) -> None:
        """Render a character from the Kaypro font onto a pixel buffer."""

        if code < 0 or code > 127:
            code = 32

        for dx in range(2, 8):
            for dy in range(8):
                x1 = x + (dx - 2) * size
                y1 = y + dy * size

                if x1 >= width or y1 >= height:
                    continue
                if x1 < 0 or y1 < 0:
                    continue

                is_set = bool(Kaypro2Font.BITS[code * 8 + dy] & (0x80 >> dx))

                if not is_set:
                    continue

                for mx in range(size):
                    for my in range(size):
                        xi = x1 + mx
                        yi = y1 + my
                        if 0 <= xi < width and 0 <= yi < height:
                            pixels[xi, yi] = color

    @staticmethod
    def convert_text(text: str) -> ConvertedText:
        """Convert input text into Kaypro character codes.

        The conversion supports escape sequences of the form ``\\NNN``.
        """

        lines = re.split(r"\r\n|\r|\n", text)
        if not lines:
            return ConvertedText([[32] for _ in range(Kaypro2Font.MAX_COLUMNS)], 1)

        data: List[List[int]] = [
            [32 for _ in range(len(lines))] for _ in range(Kaypro2Font.MAX_COLUMNS)
        ]

        y = 0
        for line in lines:
            if y >= len(lines):
                break

            x = 0
            esc_remain = 0
            esc_code = 0

            for char in line:
                if x >= Kaypro2Font.MAX_COLUMNS:
                    if esc_remain > 0:
                        raise ValueError(
                            f"Invalid escape code on line {y + 1}:\n\n{line}\n"
                        )
                    break

                if esc_remain > 0:
                    if not char.isdigit():
                        raise ValueError(
                            f"Invalid escape code on line {y + 1}:\n\n{line}\n"
                        )
                    esc_code += int(char) * (10 ** (esc_remain - 1))
                    esc_remain -= 1

                    if esc_remain == 0:
                        if not 0 <= esc_code <= 127:
                            raise ValueError(
                                f"Invalid escape code on line {y + 1}:\n\n{line}\n"
                            )
                        data[x][y] = esc_code
                        x += 1
                elif char == "\\":
                    esc_remain = 3
                    esc_code = 0
                else:
                    data[x][y] = ord(char)
                    x += 1

            if esc_remain > 0:
                raise ValueError(
                    f"Invalid escape code on line {y + 1}:\n\n{line}\n"
                )

            y += 1

        return ConvertedText(data=data, length=y)
